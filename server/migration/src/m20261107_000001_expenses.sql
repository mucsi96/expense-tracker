-- Adopt an existing, fully migrated schema without touching rows, identities,
-- sequences or Liquibase history. Only an empty schema is initialized.
DO $$
BEGIN
    IF to_regclass('expensetracker.expenses') IS NOT NULL THEN
        IF to_regclass('expensetracker.categories') IS NULL
           OR to_regclass('expensetracker.merchant_categories') IS NULL
           OR to_regclass('expensetracker.settings') IS NULL
           OR NOT EXISTS (SELECT 1 FROM information_schema.columns
                          WHERE table_schema = 'expensetracker'
                          AND table_name = 'settings' AND column_name = 'monthly_budget') THEN
            RAISE EXCEPTION 'Existing expense schema is incomplete; apply the previous release migrations first';
        END IF;
        RETURN;
    END IF;
    CREATE TABLE expensetracker.expenses (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        expense_date TIMESTAMPTZ, description TEXT, location TEXT, category TEXT,
        amount NUMERIC(19,4), currency TEXT, converted_amount NUMERIC(19,4),
        base_currency TEXT, method TEXT, type TEXT, comment TEXT
    );
    CREATE TABLE expensetracker.categories (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL UNIQUE, emoji TEXT, description TEXT
    );
    CREATE TABLE expensetracker.merchant_categories (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        merchant TEXT NOT NULL UNIQUE, category TEXT NOT NULL
    );
    CREATE TABLE expensetracker.settings (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        closing_day INTEGER NOT NULL, monthly_budget NUMERIC(11,2) NOT NULL DEFAULT 0
    );
    INSERT INTO expensetracker.settings (closing_day) VALUES (31);
END $$;
